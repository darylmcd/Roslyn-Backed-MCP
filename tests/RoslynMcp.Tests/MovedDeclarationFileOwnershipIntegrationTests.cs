    private static string CompilationPolicy(CSharpCompilationOptions options) => JsonSerializer.Serialize(new
    {
        options.OutputKind,
        options.ModuleName,
        options.MainTypeName,
        options.ScriptClassName,
        options.Usings,
        options.OptimizationLevel,
        options.CheckOverflow,
        options.AllowUnsafe,
        options.CryptoKeyContainer,
        options.CryptoKeyFile,
        options.CryptoPublicKey,
        options.DelaySign,
        options.PublicSign,
        options.Platform,
        options.GeneralDiagnosticOption,
        options.WarningLevel,
        SpecificDiagnosticOptions = options.SpecificDiagnosticOptions.OrderBy(p => p.Key, StringComparer.Ordinal),
        options.ConcurrentBuild,
        options.Deterministic,
        options.MetadataImportOptions,
        options.ReportSuppressedDiagnostics,
        options.NullableContextOptions,
        MetadataReferenceResolver = ResolverSettings(options.MetadataReferenceResolver),
        SourceReferenceResolver = ResolverSettings(options.SourceReferenceResolver),
        XmlReferenceResolver = ResolverSettings(options.XmlReferenceResolver),
        StrongNameProvider = ResolverSettings(options.StrongNameProvider),
        SyntaxTreeOptionsProvider = options.SyntaxTreeOptionsProvider?.GetType().FullName,
        AssemblyIdentityComparer = options.AssemblyIdentityComparer.GetType().FullName,
    });

    private static string ResolverSettings(object? resolver)
    {
        if (resolver is null) return "null";
        var settings = new SortedDictionary<string, object?>(StringComparer.Ordinal)
        {
            ["Type"] = resolver.GetType().FullName,
        };
        foreach (var property in resolver.GetType().GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(p => p.CanRead && p.GetIndexParameters().Length == 0))
        {
            var value = property.GetValue(resolver);
            settings[property.Name] = value switch
            {
                null => null,
                string or bool or int or long or Enum => value,
                IEnumerable<string> strings => strings.ToArray(),
                IEnumerable<KeyValuePair<string, string>> pairs => pairs.OrderBy(p => p.Key, StringComparer.Ordinal).ToArray(),
                _ => value.GetType().FullName,
            };
        }
        return JsonSerializer.Serialize(settings);
    }

    private static string Prefix(string ns) => ns.Length == 0 ? "" : ns + ".";
    private static string FullName(string ns) => Prefix(ns) + "OwnedType";
    private static int Count(string text, string marker) => text.Split(marker, StringSplitOptions.None).Length - 1;

    private static void SetPolicy(string path, string language, string nullable)
    {
        var xml = XDocument.Load(path);
        xml.Root!.Add(new XElement("PropertyGroup", new XElement("LangVersion", language),
            new XElement("Nullable", nullable), new XElement("ImplicitUsings", "disable")));
        xml.Save(path);
    }

    private static async Task<string> SymbolContextAsync(Solution solution, string projectName, string metadataName, bool expectedGenerated)
    {
        var compilation = (await solution.Projects.Single(p => p.Name == projectName).GetCompilationAsync())!;
        var type = compilation.GetTypeByMetadataName(metadataName)!;
        Assert.IsNotNull(type, metadataName);
        var declaration = await type.DeclaringSyntaxReferences.Single().GetSyntaxAsync();
        var generated = typeof(Compilation).Assembly.GetType("Roslyn.Utilities.GeneratedCodeUtilities")!
            .GetMethods(BindingFlags.Static | BindingFlags.NonPublic | BindingFlags.Public)
            .Single(m => m.Name == "IsGeneratedCode" && m.GetParameters().Length == 3 && m.GetParameters()[0].ParameterType == typeof(SyntaxTree));
        var classified = generated.Invoke(null, [declaration.SyntaxTree,
            new Func<SyntaxTrivia, bool>(t => t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia)), CancellationToken.None]);
        Assert.AreEqual(expectedGenerated, classified, "Compiler generated classification is an independent oracle.");
        var methods = type.GetMembers().OfType<IMethodSymbol>().Where(m => m.MethodKind == MethodKind.Ordinary)
            .OrderBy(m => m.Name).Select(m => m.Name + ":" + NullableShape(m.ReturnType) + ":" +
                string.Join(",", m.Parameters.Select(p => NullableShape(p.Type))));
        return type.GetDocumentationCommentXml()!.Replace(metadataName, "TYPE", StringComparison.Ordinal) + string.Join("|", methods);
    }

    private static string NullableShape(ITypeSymbol type) => type.NullableAnnotation + ":" + type.TypeKind +
        (type is INamedTypeSymbol named ? "[" + string.Join(",", named.TypeArguments.Select(NullableShape)) + "]" : "");

    private static async Task AssertRuntimeAsync(Solution solution, string projectName, string metadataName, bool imported)
    {
        var compilation = (await solution.Projects.Single(p => p.Name == projectName).GetCompilationAsync())!;
        using var bytes = new MemoryStream();
        var result = compilation.Emit(bytes);
        Assert.IsTrue(result.Success, string.Join(Environment.NewLine, result.Diagnostics));
        bytes.Position = 0;
        var context = new AssemblyLoadContext("MovedOwnership_" + Guid.NewGuid().ToString("N"), true);
        try
        {
            var type = context.LoadFromStream(bytes).GetType(metadataName)!;
            Assert.AreEqual(11, type.GetMethod("Echo")!.Invoke(null, [7]));
            if (imported) Assert.AreEqual("bound", type.GetMethod("Imported")!.Invoke(Activator.CreateInstance(type), null));
        }
        finally { context.Unload(); }
    }
