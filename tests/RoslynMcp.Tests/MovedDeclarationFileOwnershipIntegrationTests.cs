    public static IEnumerable<object[]> OwnershipCases()
    {
        foreach (var route in new[] { "move", "relocate" })
            foreach (var shape in route == "move" ? new[] { "member", "namespace", "using" } : new[] { "namespace", "using" })
                foreach (var first in new[] { false, true })
                    foreach (var explicitNullable in new[] { false, true })
                        yield return [route, shape, first, explicitNullable, "14.0", "explicit", "eof"];
        yield return ["move", "member", true, false, "7.3", "global", "eof"];
        yield return ["move", "member", false, false, "9.0", "global", "eof"];
        yield return ["move", "namespace", true, true, "10.0", "preserve", "no-newline"];
        yield return ["move", "using", true, true, "10.0", "derive", "delete"];
        yield return ["relocate", "namespace", true, true, "10.0", "explicit", "delete"];
        yield return ["relocate", "namespace", false, false, "14.0", "explicit", "no-newline"];
        foreach (var route in new[] { "move", "relocate" })
        {
            yield return [route, "using", true, true, "14.0", "explicit", "region"];
            yield return [route, "namespace", true, true, "14.0", "explicit", "conditional"];
            foreach (var shape in new[] { "imports", "imports-block", "imports-relative", "imports-nested", "imports-plain", "documentation" })
                yield return [route, shape, false, true, "14.0", "explicit", "eof"];
        }
    }

    [TestMethod]
    [DynamicData(nameof(OwnershipCases))]
    public async Task Native_Move_Preserves_File_And_Declaration_Roles(
        string route, string shape, bool selectedFirst, bool explicitNullable, string language, string selection, string tail)
    {
        await using var workspace = CreateIsolatedWorkspaceCopy();
        AddProjectToCopiedSolution(workspace.RootPath, "Contracts", "net10.0");
        var targetProjectPath = workspace.GetPath("Contracts", "Contracts.csproj");
        SetPolicy(targetProjectPath, language, language is "7.3" or "9.0" ? "disable" : "enable");
        var sourcePath = workspace.GetPath("SampleLib", "Ownership.cs");
        var targetPath = workspace.GetPath(route == "move" ? "Contracts" : "SampleLib", route == "move" ? "Ownership.cs" : "Moved.cs");
        var hasImport = shape.StartsWith("imports", StringComparison.Ordinal);
        var generated = shape != "documentation";
        const string selectedDocs = "/// <summary>SELECTED DOC</summary>\r\n";
        const string other = "/// <summary>OTHER DOC</summary>\r\npublic class Other { public string Identity(string value) => value; }\r\n";
        var selected = selectedDocs +
            "public class OwnedType\r\n{\r\n" +
            "    public static int Echo(int value) { const string literal = @\"a  b\"; return value + literal.Length; }\r\n" +
            "    public string Identity(string value) => value;\r\n" +
            "    public System.Collections.Generic.List<string> Nested(System.Collections.Generic.List<string> value) => value;\r\n" +
            (hasImport ? "    public string Imported() => new " + (shape == "imports-plain" ? "StringBuilder" : "Builder") + "(\"bound\").ToString();\r\n" : "") +
            "} // member-tail" + (tail == "no-newline" ? "" : "\r\n");
        var prelude = (generated ? "// <auto-generated/>\r\n" : "") + (explicitNullable ? "#nullable enable\r\n" : "");
        var regionStart = tail == "region" ? "#region ownership\r\n" : tail == "conditional" ? "#if true\r\n" :
            tail == "local-policy" ? "#nullable enable\r\n#pragma warning disable CS1591\r\n" : "";
        var regionEnd = tail == "region" ? "#endregion\r\n" : tail == "conditional" ? "#endif\r\n" : "";
        var declarations = tail == "delete" ? selected : selectedFirst ? selected + other : other + selected;
        if (tail == "no-newline") declarations = other + selected;
        var sourceNamespace = shape switch { "member" => "", "imports-relative" => "System.Original", "imports-nested" => "Original.Nested", _ => "Original" };
        var source = prelude + (shape is "using" or "imports" ? "using System;\r\n" : "") +
            (sourceNamespace.Length == 0 ? "" : "namespace Original;\r\n") +
            (shape == "imports" ? "using Builder = global::System.Text.StringBuilder;\r\n" : "") +
            regionStart + declarations + (regionEnd.Length == 0 ? "" : regionEnd) +
            (tail == "eof" ? "// file-tail\r\n" : "");
        if (shape is "imports-block" or "imports-relative" or "imports-nested" or "imports-plain")
        {
            var imports = shape == "imports-plain" ? "using System.Text;\r\n" : "using Builder = global::System.Text.StringBuilder;\r\n";
            source = shape switch
            {
                "imports-relative" => prelude + "namespace System\r\n{\r\nusing Builder = Text.StringBuilder;\r\nnamespace Original\r\n{\r\n" + declarations + "}\r\n}\r\n// file-tail\r\n",
                "imports-nested" => prelude + "namespace Original\r\n{\r\nusing Builder = global::System.IO.StringWriter;\r\nnamespace Nested\r\n{\r\n" + imports + declarations + "}\r\n}\r\n// file-tail\r\n",
                _ => prelude + "namespace Original\r\n{\r\n" + imports + declarations + "}\r\n// file-tail\r\n",
            };
        }
        await File.WriteAllTextAsync(sourcePath, source);
        var sourceBytes = await File.ReadAllBytesAsync(sourcePath);
        var sourceProjectPath = workspace.GetPath("SampleLib", "SampleLib.csproj");
        var projectBytes = await File.ReadAllBytesAsync(targetProjectPath);
        var sourceProjectBytes = await File.ReadAllBytesAsync(sourceProjectPath);
        await workspace.LoadAsync();
        var before = WorkspaceManager.GetCurrentSolution(workspace.WorkspaceId);
        await AssertCompilesAsync(before);
        await AssertRuntimeAsync(before, "SampleLib", FullName(sourceNamespace), hasImport);
        var sourceDocument = before.Projects.Single(p => p.Name == "SampleLib").Documents.Single(d => d.FilePath == sourcePath);
        var sourceRoot = (CompilationUnitSyntax)(await sourceDocument.GetSyntaxRootAsync())!;
        var original = sourceRoot.DescendantNodes().OfType<ClassDeclarationSyntax>().Single(c => c.Identifier.ValueText == "OwnedType");
        var originalBody = original.ToString();
        var originalEof = sourceRoot.EndOfFileToken.ToFullString();
        var selectedContext = await SymbolContextAsync(before, "SampleLib", FullName(sourceNamespace), generated);
        var otherContext = tail == "delete" ? null : await SymbolContextAsync(before, "SampleLib", Prefix(sourceNamespace) + "Other", generated);
        var originalVersion = WorkspaceManager.GetCurrentVersion(workspace.WorkspaceId);
        var options = before.Projects.ToDictionary(p => p.FilePath!, p => (p.ParseOptions, p.CompilationOptions, Policy: CompilationPolicy((CSharpCompilationOptions)p.CompilationOptions!)), StringComparer.OrdinalIgnoreCase);
        var json = route == "move"
            ? await CrossProjectRefactoringTools.PreviewMoveTypeToProject(WorkspaceExecutionGate, CrossProjectRefactoringService,
                workspace.WorkspaceId, sourcePath, "OwnedType", "Contracts", selection == "explicit" ? "Chosen" : null,
                CancellationToken.None, preserveNamespace: selection is "preserve" or "global")
            : await TypeMoveTools.PreviewChangeTypeNamespace(WorkspaceExecutionGate,
                new NamespaceRelocationService(WorkspaceManager, PreviewStore, NullLogger<NamespaceRelocationService>.Instance),
                workspace.WorkspaceId, "OwnedType", sourceNamespace, "Chosen", targetPath);
        var preview = JsonSerializer.Deserialize<RefactoringPreviewDto>(json, new JsonSerializerOptions { PropertyNameCaseInsensitive = true })!;
        Assert.IsFalse(string.IsNullOrWhiteSpace(preview.PreviewToken), json);
        var entry = PreviewStore.Retrieve(preview.PreviewToken);
        Assert.IsNotNull(entry);
        var pending = await ReparseSerializedDocumentsAsync(entry.Value.ModifiedSolution);
        var targetProjectName = route == "move" ? "Contracts" : "SampleLib";
        var targetNamespace = selection switch { "global" => "", "preserve" => sourceNamespace, "derive" => "Contracts", _ => "Chosen" };
        await VerifyAsync(pending);
        Assert.AreSame(before, WorkspaceManager.GetCurrentSolution(workspace.WorkspaceId));
        Assert.AreEqual(originalVersion, WorkspaceManager.GetCurrentVersion(workspace.WorkspaceId));
        CollectionAssert.AreEqual(sourceBytes, await File.ReadAllBytesAsync(sourcePath));
        CollectionAssert.AreEqual(projectBytes, await File.ReadAllBytesAsync(targetProjectPath));
        CollectionAssert.AreEqual(sourceProjectBytes, await File.ReadAllBytesAsync(sourceProjectPath));
        Assert.IsFalse(File.Exists(targetPath));
        var targetText = (await pending.GetDocument(pending.Projects.Single(p => p.Name == targetProjectName)
            .Documents.Single(d => d.FilePath == targetPath).Id)!.GetTextAsync()).ToString();
        var applied = await RefactoringService.ApplyRefactoringAsync(preview.PreviewToken, "ownership_test", CancellationToken.None);
        Assert.IsTrue(applied.Success, applied.Error);
        Assert.IsTrue(WorkspaceManager.GetCurrentVersion(workspace.WorkspaceId) > originalVersion);
        Assert.IsNull(PreviewStore.Retrieve(preview.PreviewToken));
        Assert.AreEqual(targetText, await File.ReadAllTextAsync(targetPath));
        AssertOptions(WorkspaceManager.GetCurrentSolution(workspace.WorkspaceId), reloaded: false);
        await workspace.ReloadAsync();
        await VerifyAsync(await ReparseSerializedDocumentsAsync(WorkspaceManager.GetCurrentSolution(workspace.WorkspaceId)), reloaded: true);
        CollectionAssert.AreEqual(projectBytes, await File.ReadAllBytesAsync(targetProjectPath));
        if (route == "relocate") CollectionAssert.AreEqual(sourceProjectBytes, await File.ReadAllBytesAsync(sourceProjectPath));
        if (tail == "delete") Assert.IsFalse(File.Exists(sourcePath));
        else
        {
            var remainingText = await File.ReadAllTextAsync(sourcePath);
            Assert.IsTrue(remainingText.StartsWith(prelude, StringComparison.Ordinal));
            Assert.AreEqual(0, Count(remainingText, "SELECTED DOC"));
            Assert.AreEqual(generated ? 1 : 0, Count(remainingText, "// <auto-generated/>"));
        }

        void AssertOptions(Solution solution, bool reloaded)
        {
            foreach (var project in solution.Projects)
            {
                Assert.AreEqual(options[project.FilePath!].ParseOptions, project.ParseOptions);
                if (!reloaded)
                    Assert.AreEqual(options[project.FilePath!].CompilationOptions, project.CompilationOptions);
                Assert.AreEqual(options[project.FilePath!].Policy, CompilationPolicy((CSharpCompilationOptions)project.CompilationOptions!));
            }
        }

        async Task VerifyAsync(Solution solution, bool reloaded = false)
        {
            await AssertCompilesAsync(solution);
            AssertOptions(solution, reloaded);
            var document = solution.Projects.Single(p => p.Name == targetProjectName).Documents.Single(d => d.FilePath == targetPath);
            var root = (CompilationUnitSyntax)(await document.GetSyntaxRootAsync())!;
            var text = (await document.GetTextAsync()).ToString();
            Assert.IsTrue(text.StartsWith(prelude, StringComparison.Ordinal), "Physical file prelude must precede namespace/imports.");
            Assert.AreEqual(generated ? 1 : 0, Count(text, "// <auto-generated/>"));
            Assert.AreEqual(0, Count(text, "OTHER DOC"));
            Assert.AreEqual(1, Count(text, "SELECTED DOC"));
            var moved = root.DescendantNodes().OfType<ClassDeclarationSyntax>().Single();
            Assert.AreEqual(originalBody, moved.ToString(), "Declaration body/literals are byte-preserved.");
            Assert.AreEqual(selectedDocs, string.Concat(moved.GetLeadingTrivia().Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)).Select(t => t.ToFullString())));
            Assert.AreEqual(originalEof, root.EndOfFileToken.ToFullString(), "Actual EOF token is preserved.");
            Assert.AreEqual(selectedContext, await SymbolContextAsync(solution, targetProjectName, FullName(targetNamespace), generated));
            if (otherContext is not null)
                Assert.AreEqual(otherContext, await SymbolContextAsync(solution, "SampleLib", Prefix(sourceNamespace) + "Other", generated));
            if (tail == "local-policy")
            {
                var remaining = solution.Projects.Single(p => p.Name == "SampleLib").Documents.Single(d => d.FilePath == sourcePath);
                var remainingText = (await remaining.GetTextAsync()).ToString();
                foreach (var directive in new[] { "#nullable enable", "#pragma warning disable CS1591" })
                {
                    Assert.AreEqual(1, Count(text, directive));
                    Assert.AreEqual(1, Count(remainingText, directive));
                }
            }
            await AssertRuntimeAsync(solution, targetProjectName, FullName(targetNamespace), hasImport);
        }
    }

